import { describe, expect, it } from 'vitest';
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import { protectPdf } from './protect';
import { unlockPdf } from './unlock';
import { isEncrypted } from '@pdfsmaller/pdf-decrypt';

const tmpDir = path.resolve('/tmp/intabpdf-audit');
if (!fs.existsSync(tmpDir)) {
  fs.mkdirSync(tmpDir, { recursive: true });
}

async function createRichTestPdf(): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle('Security Audit Document');
  doc.setAuthor('InTabPDF QA');
  doc.setSubject('Interoperability Verification');

  const font = await doc.embedFont(StandardFonts.Helvetica);
  const page1 = doc.addPage([500, 700]);
  page1.drawText('Security Audit: Form & Annotation Integrity', {
    x: 50,
    y: 650,
    size: 16,
    font,
    color: rgb(0.1, 0.1, 0.1),
  });

  // Add AcroForm fields
  const form = doc.getForm();
  const nameField = form.createTextField('auditor.name');
  nameField.setText('Antigravity Auditor');
  nameField.addToPage(page1, { x: 50, y: 580, width: 220, height: 26 });

  const agreeCheck = form.createCheckBox('audit.verified');
  agreeCheck.check();
  agreeCheck.addToPage(page1, { x: 50, y: 530, width: 20, height: 20 });

  // Add Page 2 with embedded image
  const page2 = doc.addPage([500, 700]);
  const pngBase64 =
    'iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAYAAABytg0kAAAAFElEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==';
  const img = await doc.embedPng(Buffer.from(pngBase64, 'base64'));
  page2.drawImage(img, { x: 50, y: 450, width: 120, height: 120 });
  page2.drawText('Page 2: Vector and Image Payload', {
    x: 50,
    y: 600,
    size: 14,
    font,
  });

  return await doc.save();
}

describe('Security & Interoperability Audit: Protect and Unlock PDF', () => {
  it('protects rich PDF with AES-256 and passes independent qpdf and Poppler inspection', async () => {
    const rawPdf = await createRichTestPdf();
    const protectedBytes = await protectPdf(rawPdf, {
      password: 'AuditSecretPass123!',
      algorithm: 'AES-256',
      allowPrinting: true,
      allowCopying: false,
    });

    const protectedPath = path.join(tmpDir, 'test-protected-aes256.pdf');
    fs.writeFileSync(protectedPath, protectedBytes);

    // 1. Without password, qpdf must fail to open
    expect(() => {
      execSync(`qpdf --check "${protectedPath}"`, { stdio: 'pipe' });
    }).toThrow();

    // 2. With wrong password, qpdf must fail to open
    expect(() => {
      execSync(`qpdf --password=wrongpass "${protectedPath}" --check`, { stdio: 'pipe' });
    }).toThrow();

    // 3. With correct password, qpdf --check must succeed with 0 exit code
    const qpdfCheckOut = execSync(
      `qpdf --password=AuditSecretPass123! "${protectedPath}" --check`,
      { encoding: 'utf-8' }
    );
    expect(qpdfCheckOut).toContain('checking');

    // 4. Verify qpdf detects Standard Security Handler Revision 6 (AES-256)
    const encInfo = execSync(
      `qpdf --show-encryption --password=AuditSecretPass123! "${protectedPath}"`,
      { encoding: 'utf-8' }
    );
    expect(encInfo).toMatch(/R\s*=\s*6/i);
    expect(encInfo).toMatch(/AESv3/i);

    // 5. Verify Poppler pdfinfo reads the protected file with password
    const pdfInfoOut = execSync(
      `pdfinfo -upw AuditSecretPass123! "${protectedPath}"`,
      { encoding: 'utf-8' }
    );
    expect(pdfInfoOut).toContain('Pages:');
    expect(pdfInfoOut).toContain('2');
    expect(pdfInfoOut).toContain('Security Audit Document');
  });

  it('protects rich PDF with RC4-128 and passes independent qpdf inspection', async () => {
    const rawPdf = await createRichTestPdf();
    const protectedBytes = await protectPdf(rawPdf, {
      password: 'Rc4AuditPass456',
      algorithm: 'RC4',
      allowPrinting: false,
      allowCopying: false,
    });

    const protectedPath = path.join(tmpDir, 'test-protected-rc4.pdf');
    fs.writeFileSync(protectedPath, protectedBytes);

    // Verify qpdf identifies Revision 3 (RC4 128-bit)
    const encInfo = execSync(
      `qpdf --show-encryption --password=Rc4AuditPass456 "${protectedPath}"`,
      { encoding: 'utf-8' }
    );
    expect(encInfo).toMatch(/R\s*=\s*3/i);

    // Correct password passes qpdf --check
    const qpdfCheckOut = execSync(
      `qpdf --password=Rc4AuditPass456 "${protectedPath}" --check`,
      { encoding: 'utf-8' }
    );
    expect(qpdfCheckOut).toContain('checking');
  });

  it('unlocks an independently encrypted PDF generated by qpdf (AES-256) using user password', async () => {
    const rawPdf = await createRichTestPdf();
    const rawPath = path.join(tmpDir, 'raw-for-qpdf.pdf');
    const qpdfEncPath = path.join(tmpDir, 'independently-encrypted-qpdf-aes256.pdf');
    fs.writeFileSync(rawPath, rawPdf);

    // Generate encrypted PDF via external qpdf CLI tool with standard indirect objects
    execSync(
      `qpdf --object-streams=disable --encrypt ExternalUser2026 ExternalOwner2026 256 -- "${rawPath}" "${qpdfEncPath}"`
    );

    const qpdfEncBytes = fs.readFileSync(qpdfEncPath);
    const encStatus = await isEncrypted(qpdfEncBytes);
    expect(encStatus.encrypted).toBe(true);

    // Unlock using Unlock PDF tool
    const unlockedBytes = await unlockPdf(new Uint8Array(qpdfEncBytes), {
      password: 'ExternalUser2026',
    });

    const unlockedPath = path.join(tmpDir, 'unlocked-from-qpdf.pdf');
    fs.writeFileSync(unlockedPath, unlockedBytes);

    // Independent validation: qpdf opens with NO password
    const checkOut = execSync(`qpdf --check "${unlockedPath}"`, { encoding: 'utf-8' });
    expect(checkOut).toContain('checking');

    // Poppler pdfinfo opens with NO password and preserves metadata and 2 pages
    const pdfInfoOut = execSync(`pdfinfo "${unlockedPath}"`, { encoding: 'utf-8' });
    expect(pdfInfoOut).toContain('Pages:');
    expect(pdfInfoOut).toContain('2');
    expect(pdfInfoOut).toContain('Security Audit Document');
  });

  it('unlocks an independently encrypted PDF using owner password', async () => {
    const qpdfEncPath = path.join(tmpDir, 'independently-encrypted-qpdf-aes256.pdf');
    const qpdfEncBytes = fs.readFileSync(qpdfEncPath);

    const unlockedWithOwner = await unlockPdf(new Uint8Array(qpdfEncBytes), {
      password: 'ExternalOwner2026',
    });

    const unlockedPath = path.join(tmpDir, 'unlocked-with-owner.pdf');
    fs.writeFileSync(unlockedPath, unlockedWithOwner);

    const checkOut = execSync(`qpdf --check "${unlockedPath}"`, { encoding: 'utf-8' });
    expect(checkOut).toContain('checking');
  });

  it('unlocks an independently encrypted 128-bit PDF generated by qpdf', async () => {
    const rawPath = path.join(tmpDir, 'raw-for-qpdf.pdf');
    const qpdf128Path = path.join(tmpDir, 'independently-encrypted-qpdf-128.pdf');

    execSync(
      `qpdf --allow-weak-crypto --object-streams=disable --encrypt User128Pass Owner128Pass 128 -- "${rawPath}" "${qpdf128Path}"`
    );

    const qpdf128Bytes = fs.readFileSync(qpdf128Path);
    const unlocked128 = await unlockPdf(new Uint8Array(qpdf128Bytes), {
      password: 'User128Pass',
    });

    const unlockedPath = path.join(tmpDir, 'unlocked-128.pdf');
    fs.writeFileSync(unlockedPath, unlocked128);

    const checkOut = execSync(`qpdf --check "${unlockedPath}"`, { encoding: 'utf-8' });
    expect(checkOut).toContain('checking');

    const pdfInfoOut = execSync(`pdfinfo "${unlockedPath}"`, { encoding: 'utf-8' });
    expect(pdfInfoOut).toContain('Pages:');
    expect(pdfInfoOut).toContain('2');
  });

  it('rejects encrypted object stream PDFs with a clear unsupported variant error', async () => {
    const rawPath = path.join(tmpDir, 'raw-for-qpdf.pdf');
    const qpdfObjStmPath = path.join(tmpDir, 'qpdf-objstm-encrypted.pdf');

    // Generate an encrypted PDF with object streams enabled
    execSync(
      `qpdf --object-streams=generate --encrypt ObjUser ObjOwner 256 -- "${rawPath}" "${qpdfObjStmPath}"`
    );

    const bytes = fs.readFileSync(qpdfObjStmPath);
    await expect(
      unlockPdf(new Uint8Array(bytes), { password: 'ObjUser' })
    ).rejects.toThrow(
      'This PDF uses encrypted object streams (/ObjStm), which is not supported by client-side decryption.'
    );
  });

  it('preserves form field data and annotations after unlock', async () => {
    const unlockedPath = path.join(tmpDir, 'unlocked-from-qpdf.pdf');
    const unlockedBytes = fs.readFileSync(unlockedPath);

    const doc = await PDFDocument.load(unlockedBytes);
    const form = doc.getForm();
    const nameField = form.getTextField('auditor.name');
    expect(nameField.getText()).toBe('Antigravity Auditor');

    const agreeCheck = form.getCheckBox('audit.verified');
    expect(agreeCheck.isChecked()).toBe(true);
  });
});
